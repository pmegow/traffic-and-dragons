const assert=require('assert/strict');
const E=require('./audio-envelope.js');
const p=[{time:0,gain:1},{time:.4,gain:1},{time:1.2844,gain:0}];
assert.equal(E.gainAt(.4,p,'exponential',6.907755),1);
assert.equal(E.gainAt(1.2844,p,'exponential',6.907755),0);
assert(E.gainAt(.8,p,'exponential',6.907755)<.05);
assert.equal(E.gainAt(.5,[{time:0,gain:0},{time:1,gain:1}],'linear',5),.5);
assert.equal(E.gainAt(0,p,'cosine',5),1);
for(const points of [[{time:0,gain:1},{time:0,gain:0}],[{time:0,gain:NaN},{time:1,gain:0}],[{time:0,gain:1},{time:1,gain:2}]])assert.throws(()=>E.validate(points,1));
assert.throws(()=>E.validate(p,1));
const input=[new Float32Array([1,1,1,1,1]),new Float32Array([-.5,-.5,-.5,-.5,-.5])];
const rendered=E.render(input,4,0,1,[{time:0,gain:1},{time:1,gain:0}],'linear',4);
assert.deepEqual(Array.from(rendered[0]),[1,2/3,1/3,0].map(Math.fround));
assert.deepEqual(Array.from(rendered[1]),[-.5,-1/3,-1/6,-0].map(Math.fround));
assert.deepEqual(Array.from(input[0]),[1,1,1,1,1],'source PCM unchanged');
assert.throws(()=>E.render(input,4,.7,.6,p,'linear',5));
const wav=E.wav(rendered,4),v=new DataView(wav);
assert.equal(v.getUint16(22,true),2,'stereo retained');assert.equal(v.getUint32(40,true),16);assert.equal(v.getInt16(44,true),32767);assert.equal(v.getInt16(46,true),-16384);assert.equal(v.getInt16(wav.byteLength-2,true),0,'ends at silence');
console.log('AUDIO ENVELOPE GREEN: point validation, exponential/linear/cosine, exact endpoints, stereo render, immutable source, WAV export');
